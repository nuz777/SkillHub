-- ========================================================
-- SkillHub Database Script (PostgreSQL)
-- Schema & Initial Seed Data
-- ========================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Tablas de ASP.NET Core Identity
CREATE TABLE IF NOT EXISTS "AspNetRoles" (
    "Id" text NOT NULL PRIMARY KEY,
    "Name" character varying(256),
    "NormalizedName" character varying(256),
    "ConcurrencyStamp" text
);

CREATE TABLE IF NOT EXISTS "AspNetUsers" (
    "Id" text NOT NULL PRIMARY KEY,
    "UserName" character varying(256),
    "NormalizedUserName" character varying(256),
    "Email" character varying(256),
    "NormalizedEmail" character varying(256),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text,
    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL,
    "FullName" text NOT NULL DEFAULT '',
    "Specialty" text
);

CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
    "UserId" text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
    "RoleId" text NOT NULL REFERENCES "AspNetRoles"("Id") ON DELETE CASCADE,
    PRIMARY KEY ("UserId", "RoleId")
);

CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId" text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
    "ClaimType" text,
    "ClaimValue" text
);

CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text,
    "UserId" text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
    PRIMARY KEY ("LoginProvider", "ProviderKey")
);

CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
    "UserId" text NOT NULL REFERENCES "AspNetUsers"("Id") ON DELETE CASCADE,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,
    PRIMARY KEY ("UserId", "LoginProvider", "Name")
);

CREATE TABLE IF NOT EXISTS "AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RoleId" text NOT NULL REFERENCES "AspNetRoles"("Id") ON DELETE CASCADE,
    "ClaimType" text,
    "ClaimValue" text
);

-- 2. Entidades de Dominio de SkillHub
CREATE TABLE IF NOT EXISTS "Instructors" (
    "Id" uuid NOT NULL PRIMARY KEY DEFAULT uuid_generate_v4(),
    "FullName" character varying(150) NOT NULL,
    "Email" character varying(150) NOT NULL UNIQUE,
    "Specialty" character varying(100) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone
);

CREATE TABLE IF NOT EXISTS "Workshops" (
    "Id" uuid NOT NULL PRIMARY KEY DEFAULT uuid_generate_v4(),
    "Code" character varying(20) NOT NULL UNIQUE,
    "Title" character varying(150) NOT NULL,
    "Description" character varying(1000) NOT NULL DEFAULT '',
    "InstructorId" uuid NOT NULL REFERENCES "Instructors"("Id") ON DELETE RESTRICT,
    "InstructorEmail" character varying(150) NOT NULL,
    "StartDate" timestamp with time zone NOT NULL,
    "EndDate" timestamp with time zone NOT NULL,
    "MaxCapacity" integer NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone
);

CREATE TABLE IF NOT EXISTS "Enrollments" (
    "Id" uuid NOT NULL PRIMARY KEY DEFAULT uuid_generate_v4(),
    "WorkshopId" uuid NOT NULL REFERENCES "Workshops"("Id") ON DELETE CASCADE,
    "ParticipantId" character varying(100) NOT NULL,
    "ParticipantName" character varying(150) NOT NULL,
    "ParticipantEmail" character varying(150) NOT NULL,
    "Status" integer NOT NULL, -- 1 = Active, 2 = Cancelled
    "CancelledAt" timestamp with time zone,
    "CancelledBy" character varying(150),
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone
);

CREATE INDEX IF NOT EXISTS "IX_Enrollments_ParticipantEmail_WorkshopId_Status" 
    ON "Enrollments" ("ParticipantEmail", "WorkshopId", "Status");

